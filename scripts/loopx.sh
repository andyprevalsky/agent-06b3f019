#!/usr/bin/env bash
#
# loopx.sh — meta-program: drive a Claude Code agent in a loop until a
# semantic stop condition is met, with guardrail checks and undo.
#
# Edit the variables below, then run:  bash scripts/loopx.sh
#
# Outputs:
#   .context/loopx/log.jsonl              one line per epoch + final summary
#   .context/loopx/epoch_<N>_trace.txt    raw agent output per epoch
#   .context/loopx/final_report.md        all reason traces, written on success
#
# Requires: claude CLI on PATH, jq, git.

set -uo pipefail

############################################################
# === EDIT THESE FOR EACH RUN ===============================
############################################################

# What you want the agent to accomplish. One sentence is fine; longer is fine.
GOAL=""

# Plain-language stop condition. The verifier decides "met / not met" each epoch.
# e.g. "All blackbox tests for the message_person domain pass on a clean run."
STOP_CONDITION=""

# Plain-language guardrails. Anti-reward-hacking. Each is checked at the end.
# Use one rule per line (a single string with newlines). e.g.:
#   - Do not modify any file outside back-end/src/providers/chat/
#   - Do not delete or skip tests
#   - Do not add eslint-disable or @ts-ignore
GUARDRAILS=""

# Path to a markdown file with relevant chat context. Generated by
# loopx_extract_context.py. Empty string = no extra context.
CONTEXT_FILE=".context/loopx/context.md"

# Permission mode for the inner agent. `bypassPermissions` lets it edit/run
# without prompting. Use only in worktrees you trust.
PERMISSION_MODE="bypassPermissions"

# The loop runs until the verifier says the stop condition is met or the
# guardrail check fails twice. There is no epoch cap and no budget cap —
# kill the process (Ctrl-C / `pkill -f loopx.sh`) if you need to stop early.

############################################################
# === SCRIPT (do not edit below for normal use) =============
############################################################

WORKDIR="${WORKDIR:-.context/loopx}"
LOG_FILE="$WORKDIR/log.jsonl"
REPORT_FILE="$WORKDIR/final_report.md"

mkdir -p "$WORKDIR"
: > "$LOG_FILE"

log_event() {
    # log_event <event-name> <json-extra>
    local event="$1"
    local extra="${2-}"
    [[ -z "$extra" ]] && extra='{}'
    jq -nc --arg ts "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
           --arg event "$event" \
           --argjson extra "$extra" \
           '{ts:$ts, event:$event} + $extra' >> "$LOG_FILE"
}

die() {
    echo "loopx: $*" >&2
    log_event "fatal" "$(jq -nc --arg msg "$*" '{msg:$msg}')"
    exit 1
}

[[ -z "$GOAL" ]]           && die "GOAL is empty. Edit scripts/loopx.sh."
[[ -z "$STOP_CONDITION" ]] && die "STOP_CONDITION is empty. Edit scripts/loopx.sh."
[[ -z "$GUARDRAILS" ]]     && die "GUARDRAILS is empty. Edit scripts/loopx.sh."
command -v claude >/dev/null || die "claude CLI not on PATH"
command -v jq     >/dev/null || die "jq not on PATH"
command -v git    >/dev/null || die "git not on PATH"

CONTEXT_BLOCK=""
if [[ -n "$CONTEXT_FILE" && -s "$CONTEXT_FILE" ]]; then
    CONTEXT_BLOCK=$'\n\n## Relevant chat context\n\n'"$(cat "$CONTEXT_FILE")"
fi

START_REF="$(git rev-parse HEAD 2>/dev/null || echo 'unknown')"
log_event "start" "$(jq -nc \
    --arg goal "$GOAL" \
    --arg stop "$STOP_CONDITION" \
    --arg guards "$GUARDRAILS" \
    --arg ref "$START_REF" \
    '{goal:$goal, stop_condition:$stop, guardrails:$guards, start_ref:$ref}')"

CLAUDE_BASE_FLAGS=(--print --permission-mode "$PERMISSION_MODE")

ACCUMULATED_FEEDBACK=""

run_epoch() {
    local n="$1"
    local trace_file="$WORKDIR/epoch_${n}_trace.txt"
    local prompt
    prompt="$(cat <<EOF
You are inside a /loopx run, epoch ${n}. The loop has no fixed epoch cap; it ends when the stop condition is met (or the user kills it).

# Goal
${GOAL}

# Stop condition (you are done when this is true)
${STOP_CONDITION}

# Guardrails (do NOT violate any of these)
${GUARDRAILS}

# Feedback from prior epochs (may be empty)
${ACCUMULATED_FEEDBACK:-<none>}
${CONTEXT_BLOCK}

# Instructions
- Make trustworthy progress toward the goal. Trust reasonable assumptions; do not stop to ask the user.
- Do not violate any guardrail. If a guardrail makes the goal impossible, stop and explain why instead of breaking it.
- At the end of your turn, write a short STATUS block in this exact form on the last lines of your output:

STATUS:
done: <yes|no>
summary: <one sentence describing what changed this epoch>
remaining: <one sentence describing what is left, or "none" if done>
EOF
    )"

    log_event "epoch_start" "$(jq -nc --argjson n "$n" '{epoch:$n}')"
    if ! claude "${CLAUDE_BASE_FLAGS[@]}" "$prompt" > "$trace_file" 2>&1; then
        log_event "epoch_error" "$(jq -nc --argjson n "$n" --arg trace "$trace_file" \
            '{epoch:$n, trace:$trace, msg:"claude exited non-zero"}')"
        return 1
    fi
    log_event "epoch_end" "$(jq -nc --argjson n "$n" --arg trace "$trace_file" \
        '{epoch:$n, trace:$trace}')"
    return 0
}

verify_stop() {
    local n="$1"
    local trace_file="$WORKDIR/epoch_${n}_trace.txt"
    local schema='{"type":"object","required":["met","reason"],"properties":{"met":{"type":"boolean"},"reason":{"type":"string"}}}'
    local prompt
    prompt="$(cat <<EOF
You are a strict semantic verifier. Decide whether the stop condition has been met based ONLY on the agent trace below. Be skeptical of self-reports; require evidence (test output, file edits, command results).

# Stop condition
${STOP_CONDITION}

# Agent trace (epoch ${n})
$(cat "$trace_file")

Respond with JSON: {"met": <bool>, "reason": "<one sentence>"}.
EOF
    )"

    local verdict
    verdict="$(claude --print --json-schema "$schema" "$prompt" 2>/dev/null)" || {
        log_event "verify_error" "$(jq -nc --argjson n "$n" '{epoch:$n}')"
        echo '{"met":false,"reason":"verifier failed"}'
        return
    }
    echo "$verdict"
}

check_guardrails() {
    local schema='{"type":"object","required":["violated","violations"],"properties":{"violated":{"type":"boolean"},"violations":{"type":"array","items":{"type":"object","required":["rule","evidence"],"properties":{"rule":{"type":"string"},"evidence":{"type":"string"}}}}}}'
    local diff
    diff="$(git diff "$START_REF" 2>/dev/null | head -c 60000 || true)"
    local prompt
    prompt="$(cat <<EOF
You are a strict guardrail auditor. Decide whether any guardrail was violated by the changes below. Be specific; cite file paths or commands as evidence.

# Guardrails
${GUARDRAILS}

# Git diff since loop start (truncated)
${diff}

Respond with JSON. If no violations, return {"violated": false, "violations": []}.
EOF
    )"

    claude --print --json-schema "$schema" "$prompt" 2>/dev/null || \
        echo '{"violated":false,"violations":[]}'
}

run_undo() {
    local violations_json="$1"
    local prompt
    prompt="$(cat <<EOF
You are an undo agent. The previous /loopx run violated guardrails. Revert ONLY the violating changes. Preserve other progress toward the goal.

# Original goal (do not regress this further than necessary)
${GOAL}

# Guardrails
${GUARDRAILS}

# Violations to undo (with evidence)
${violations_json}

# Current diff
$(git diff "$START_REF" 2>/dev/null | head -c 60000 || true)

Use Edit/Write/Bash as needed. End with a STATUS block:
STATUS:
reverted: <yes|no>
summary: <one sentence>
EOF
    )"
    local trace_file="$WORKDIR/undo_trace.txt"
    log_event "undo_start" "{}"
    claude "${CLAUDE_BASE_FLAGS[@]}" "$prompt" > "$trace_file" 2>&1 || true
    log_event "undo_end" "$(jq -nc --arg trace "$trace_file" '{trace:$trace}')"
}

stop_met=false
stop_reason=""
final_epoch=0
n=0

while true; do
    n=$((n + 1))
    final_epoch="$n"
    if ! run_epoch "$n"; then
        ACCUMULATED_FEEDBACK+=$'\n- Epoch '"$n"' errored; check epoch_'"$n"'_trace.txt'
        continue
    fi

    verdict_json="$(verify_stop "$n")"
    met="$(echo "$verdict_json"   | jq -r '.met // false')"
    reason="$(echo "$verdict_json" | jq -r '.reason // ""')"
    log_event "verify" "$(jq -nc --argjson n "$n" --argjson met "$met" --arg reason "$reason" \
        '{epoch:$n, met:$met, reason:$reason}')"

    if [[ "$met" == "true" ]]; then
        stop_met=true
        stop_reason="$reason"
        break
    fi
    ACCUMULATED_FEEDBACK+=$'\n- Epoch '"$n"' did not meet stop condition: '"$reason"
done

# Guardrail check (always run, even if stop not met — we still want to know)
guard_json="$(check_guardrails)"
violated="$(echo "$guard_json" | jq -r '.violated // false')"
log_event "guardrail_check" "$(jq -nc --argjson g "$guard_json" '$g')"

if [[ "$violated" == "true" ]]; then
    run_undo "$guard_json"
    # After undo, re-check guardrails once. We do NOT loop further to avoid runaway.
    guard_json2="$(check_guardrails)"
    violated2="$(echo "$guard_json2" | jq -r '.violated // false')"
    log_event "guardrail_recheck" "$(jq -nc --argjson g "$guard_json2" '$g')"
    if [[ "$violated2" == "true" ]]; then
        log_event "end" '{"status":"guardrail_violation_unresolved"}'
        echo "loopx: guardrail violation could not be auto-resolved. See $LOG_FILE." >&2
        exit 3
    fi
fi

# Build the final report
{
    echo "# loopx final report"
    echo
    echo "- Goal: $GOAL"
    echo "- Stop condition: $STOP_CONDITION"
    echo "- Stop met: $stop_met"
    [[ -n "$stop_reason" ]] && echo "- Stop reason: $stop_reason"
    echo "- Epochs run: $final_epoch"
    echo "- Start ref: $START_REF"
    echo "- End ref: $(git rev-parse HEAD 2>/dev/null || echo unknown)"
    echo
    echo "## Per-epoch traces"
    for ((n=1; n<=final_epoch; n++)); do
        local_trace="$WORKDIR/epoch_${n}_trace.txt"
        [[ -f "$local_trace" ]] || continue
        echo
        echo "### Epoch $n"
        echo
        echo '```'
        # Tail STATUS block + a bit of context (last 80 lines is plenty)
        tail -80 "$local_trace"
        echo '```'
    done
} > "$REPORT_FILE"

log_event "end" "$(jq -nc --arg reason "$stop_reason" '{status:"success", reason:$reason}')"
echo "loopx: SUCCESS. Report: $REPORT_FILE  Log: $LOG_FILE"
exit 0
