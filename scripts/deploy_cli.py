#!/usr/bin/env python3
"""One-line commands for each /deploy step (see .claude/commands/deploy-v2.md → Process).

Every subcommand composes the existing deploy tools; none adds a new gate or waiver.
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
CONTEXT = ROOT / '.context'
PR_FILE = CONTEXT / 'deploy-pr.json'
MERGED_FILE = CONTEXT / 'deploy-merged.json'
COLLECT_FILE = CONTEXT / 'deploy-collect.json'
READINESS_FILE = CONTEXT / 'deletion-readiness.json'
STATE_DIR = Path(os.environ.get('DEPLOY_TEST_CYCLE_STATE_DIR', str(CONTEXT / 'deploy-pipeline')))
LEDGER_DIR = 'agents/benchmarks/history/'
PARK_DIR = CONTEXT / 'deploy-ledger-park'
SECRET_NAMES = re.compile(r'(^|/)(\.env(\.(?!example$)[^/]+)?|[^/]*\.(pem|key|p12)|id_rsa[^/]*|credentials[^/]*\.json)$')
# Ignored paths that are regenerated by documented setup and never need preservation.
REPRODUCIBLE = ('node_modules/', '*/node_modules/', 'agents/venv/', '*/venv/', '.venv/', '*__pycache__/',
                '*.pyc', '.pytest_cache/', '*/.pytest_cache/', '.mypy_cache/', '.ruff_cache/', '*/dist/',
                '*/build/', '*/coverage/', 'coverage/', '*/test-results/', '*/playwright-report/',
                '.context/tsbuildinfo/', '.context/frontend-builds/', 'openclaw/', 'hermes-agent/', 'codex/',
                'prime-agent/', 'kimi-code/', 'htmlcov/', '*/htmlcov/', '*/.coverage', '.coverage')


def git(*args: str, cwd: Path | None = None, check: bool = True) -> str:
    return subprocess.run(['git', *args], cwd=cwd or ROOT, check=check, capture_output=True, text=True).stdout


def run(argv: list[str], cwd: Path | None = None, env: dict | None = None) -> int:
    print('$ ' + ' '.join(argv), flush=True)
    return subprocess.run(argv, cwd=cwd or ROOT, env=env).returncode


def factory(*event: str) -> None:
    code = run([sys.executable, 'scripts/record_factory_event.py', 'deploy', *event])
    if code:
        raise SystemExit(f'record_factory_event failed for {" ".join(event)} (exit {code})')


def head() -> str:
    return git('rev-parse', 'HEAD').strip()


def uncommitted(cwd: Path | None = None) -> list[str]:
    """Tracked edits and untracked non-ignored files, excluding append-only benchmark ledgers."""
    paths = git('diff', '--name-only', 'HEAD', cwd=cwd).splitlines()
    paths += git('ls-files', '--others', '--exclude-standard', cwd=cwd).splitlines()
    return sorted({p for p in paths if p and not p.startswith(LEDGER_DIR)})


def write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(payload, indent=2, sort_keys=True) + '\n')
    temp.replace(path)


def read_json(path: Path, what: str) -> dict:
    if not path.is_file():
        raise SystemExit(f'{path.relative_to(ROOT)} is missing; run `scripts/deploy {what}` first')
    return json.loads(path.read_text())


def unpushed(ref: str, cwd: Path | None = None) -> int:
    return int(git('rev-list', '--count', ref, '--not', '--remotes', cwd=cwd, check=False).strip() or 0)


# --- collect ---------------------------------------------------------------

def worktrees() -> list[dict]:
    entries, entry = [], {}
    for line in git('worktree', 'list', '--porcelain').splitlines() + ['']:
        if not line:
            if entry:
                entries.append(entry)
            entry = {}
            continue
        key, _, value = line.partition(' ')
        entry[key] = value or True
    return entries


def describe(entry: dict) -> dict:
    path = Path(entry['worktree'])
    item = {'path': str(path), 'head': entry.get('HEAD'), 'branch': entry.get('branch', 'detached'),
            'current': path.resolve() == ROOT.resolve(), 'locked': bool(entry.get('locked'))}
    if not path.is_dir():
        return {**item, 'missing': True, 'needs_integration': False}
    changes = uncommitted(path)
    ahead = unpushed('HEAD', path)
    return {**item, 'uncommitted': changes, 'unpushed_commits': ahead,
            'needs_integration': not item['current'] and bool(changes or ahead)}


def cmd_collect(args: argparse.Namespace) -> int:
    trees = [describe(entry) for entry in worktrees()]
    branches = [{'branch': ref, 'unpushed_commits': count}
                for ref in git('for-each-ref', '--format=%(refname:short)', 'refs/heads').split()
                if (count := unpushed(f'refs/heads/{ref}'))]
    write_json(COLLECT_FILE, {'worktrees': trees, 'unpushed_branches': branches})
    for tree in trees:
        mark = 'INTEGRATE' if tree.get('needs_integration') else ('current' if tree['current'] else 'ok')
        print(f"{mark:9} {tree['path']}  {tree['branch']}  uncommitted={len(tree.get('uncommitted', []))} "
              f"unpushed={tree.get('unpushed_commits', 0)}")
    for branch in branches:
        print(f"UNPUSHED  branch {branch['branch']}: {branch['unpushed_commits']} commit(s)")
    print(f'DEPLOY_COLLECT worktrees={len(trees)} integrate={sum(t.get("needs_integration", False) for t in trees)} '
          f'report={COLLECT_FILE.relative_to(ROOT)}')
    print('Also read sibling threads on this devbox (boxes-read-threads) before freezing.')
    return 0


# --- fix / freeze ----------------------------------------------------------

def cmd_fix(args: argparse.Namespace) -> int:
    sys.path.insert(0, str(ROOT / 'scripts'))
    from check_deploy_static import format_files, lint_files, prettier_binary
    from select_affected_tests import changed_files
    changed = changed_files(args.base, None)
    before = set(git('diff', '--name-only').splitlines())
    status = 0
    files = format_files(changed, args.base)
    if files:
        binary = prettier_binary()
        if binary is None:
            print('FIX: installed repository Prettier required; install pinned dependencies first', file=sys.stderr)
            return 2
        status |= run([str(binary), '--write', '--ignore-unknown', '--', *files])
    if lint := lint_files(changed):
        status |= run(['node', 'scripts/lint-affected.mjs', '--fix', *lint], cwd=ROOT / 'back-end')
    if any(path.startswith('mac-app/') for path in changed):
        if sys.platform == 'darwin':
            status |= run(['npm', 'run', 'format'], cwd=ROOT / 'mac-app')
            status |= run(['npm', 'run', 'lint:fix'], cwd=ROOT / 'mac-app')
        else:
            print('FIX: mac-app changed but its fixers are macOS-only; unverified on this platform')
    touched = sorted(set(git('diff', '--name-only').splitlines()) - before)
    print(f'DEPLOY_FIX {"PASS" if status == 0 else "FAIL"} formatted={len(files)} linted={len(lint)} '
          f'modified={len(touched)}')
    return 0 if status == 0 else 1


def cmd_freeze(args: argparse.Namespace) -> int:
    if cmd_fix(args):
        print('DEPLOY_FREEZE BLOCKED: fix the remaining format/lint errors first', file=sys.stderr)
        return 1
    pending = uncommitted()
    if secrets := [p for p in pending if SECRET_NAMES.search(p)]:
        print('DEPLOY_FREEZE BLOCKED: refusing to commit secret-looking files: ' + ', '.join(secrets), file=sys.stderr)
        return 1
    if pending:
        if not args.message:
            print('DEPLOY_FREEZE BLOCKED: uncommitted changes need --message', file=sys.stderr)
            return 1
        git('add', '-A', '--', *pending)
        git('commit', '-m', args.message)
    code = run([sys.executable, 'scripts/deploy_approval_batch.py', 'freeze', '--head', head(), '--base', args.base])
    print(f'DEPLOY_FREEZE head={head()} committed={len(pending)} approvals={"see above" if code == 0 else "error"}')
    return code


# --- PR and review ---------------------------------------------------------

def cmd_open_pr(args: argparse.Namespace) -> int:
    branch = git('branch', '--show-current').strip()
    if branch in {'', 'main'}:
        print('DEPLOY_OPEN_PR BLOCKED: deploy from a feature branch, not main or a detached HEAD', file=sys.stderr)
        return 1
    if pending := uncommitted():
        print('DEPLOY_OPEN_PR BLOCKED: uncommitted changes; run `scripts/deploy freeze` first: '
              + ', '.join(pending[:10]), file=sys.stderr)
        return 1
    sha = head()
    existing = subprocess.run(['gh', 'pr', 'view', '--json', 'number', '--jq', '.number'],
                              cwd=ROOT, capture_output=True, text=True).stdout.strip()
    if run([sys.executable, 'scripts/deploy_review_cycle.py', 'start', '--reset', '--kind', 'initial', '--head', sha]):
        return 1
    factory('stage-start', 'code-review')
    if run(['git', 'push', '-u', 'origin', branch]):
        return 1
    if existing:
        pr = int(existing)
        if run(['gh', 'pr', 'comment', str(pr), '--body', '@coderabbitai review']):
            return 1
    else:
        if not args.title:
            print('DEPLOY_OPEN_PR BLOCKED: a new PR needs --title (and --body-file)', file=sys.stderr)
            return 1
        body = ['--body-file', str(args.body_file)] if args.body_file else ['--body', '']
        created = subprocess.run(['gh', 'pr', 'create', '--base', 'main', '--title', args.title, *body],
                                 cwd=ROOT, capture_output=True, text=True)
        print(created.stdout + created.stderr, end='')
        match = re.search(r'/pull/(\d+)', created.stdout)
        if created.returncode or not match:
            return 1
        pr = int(match.group(1))
    write_json(PR_FILE, {'pr': pr, 'branch': branch, 'head': sha})
    print(f'DEPLOY_OPEN_PR pr={pr} head={sha[:12]} review=initial')
    return 0


def cmd_review_wait(args: argparse.Namespace) -> int:
    pr = read_json(PR_FILE, 'open-pr')['pr']
    state = json.loads(subprocess.run([sys.executable, 'scripts/deploy_review_cycle.py', 'status'], cwd=ROOT,
                                      check=True, capture_output=True, text=True).stdout)
    review_head = state['cycles'][-1]['head']
    return run(['bash', 'scripts/wait-for-code-review', '--pr', str(pr), '--head', review_head,
                '--timeout', str(args.timeout), '--poll', '5'])


# --- merge -----------------------------------------------------------------

def mergeable(pr: int) -> str:
    """GitHub's view of the PR against current main; the deploy never syncs main locally."""
    return subprocess.run(['gh', 'pr', 'view', str(pr), '--json', 'mergeable', '--jq', '.mergeable'],
                          cwd=ROOT, capture_output=True, text=True).stdout.strip()


def cmd_merge(args: argparse.Namespace) -> int:
    pr = read_json(PR_FILE, 'open-pr')['pr']
    sha = head()
    if pending := uncommitted():
        print('DEPLOY_MERGE BLOCKED: uncommitted changes after review: ' + ', '.join(pending[:10]), file=sys.stderr)
        return 1
    if git('log', '@{u}..HEAD', '--oneline', check=False).strip():
        print('DEPLOY_MERGE BLOCKED: unpushed commits after the final review; return to review', file=sys.stderr)
        return 1
    checks = [
        [sys.executable, 'scripts/run_deploy_pipeline.py', 'verify', '--require-staged',
         '--state-dir', str(STATE_DIR), '--expect-head', sha],
        [sys.executable, 'scripts/deploy_review_cycle.py', 'require-mergeable', '--head', sha],
        [sys.executable, 'scripts/deploy_approval_batch.py', 'check'],
    ]
    for argv in checks:
        if code := run(argv):
            print(f'DEPLOY_MERGE BLOCKED: {Path(argv[1]).name} exited {code}', file=sys.stderr)
            return 1
    if (state := mergeable(pr)) != 'MERGEABLE':
        hint = 'run /sync, rerun the affected gates, then merge' if state == 'CONFLICTING' else 'retry shortly'
        print(f'DEPLOY_MERGE BLOCKED: GitHub reports PR {pr} as {state or "unknown"}; {hint}', file=sys.stderr)
        return 1
    factory('stage-start', 'production-verify')
    if run(['gh', 'pr', 'merge', str(pr), '--merge']):
        return 1
    merged = subprocess.run(['gh', 'pr', 'view', str(pr), '--json', 'mergeCommit', '--jq', '.mergeCommit.oid'],
                            cwd=ROOT, capture_output=True, text=True).stdout.strip()
    if not re.fullmatch(r'[0-9a-f]{40}', merged):
        print(f'DEPLOY_MERGE BLOCKED: could not resolve the merge commit of PR {pr}', file=sys.stderr)
        return 1
    write_json(MERGED_FILE, {'pr': pr, 'merged_sha': merged, 'reviewed_head': sha})
    run(['git', 'fetch', 'origin', 'main'])
    print(f'DEPLOY_MERGE pr={pr} merged_sha={merged}')
    return 0


# --- deletion readiness ----------------------------------------------------

def own_pids() -> set[int]:
    pids, pid = set(), os.getpid()
    while pid > 1:
        pids.add(pid)
        try:
            stat = Path(f'/proc/{pid}/stat').read_text()
        except OSError:
            break
        pid = int(stat.rsplit(')', 1)[1].split()[1])
    return pids


def live_processes(root: Path) -> list[dict]:
    found, mine, proc = [], own_pids(), Path('/proc')
    if not proc.is_dir():
        return [{'pid': None, 'reason': '/proc unavailable; process ownership unverified'}]
    for entry in proc.iterdir():
        if not entry.name.isdigit() or int(entry.name) in mine:
            continue
        try:
            cwd = Path(os.readlink(entry / 'cwd'))
            argv = (entry / 'cmdline').read_bytes().replace(b'\0', b' ').decode(errors='replace').strip()
        except OSError:
            continue
        if cwd == root or root in cwd.parents:
            found.append({'pid': int(entry.name), 'cwd': str(cwd), 'argv': argv[:200]})
    return found


def ignored_paths(root: Path) -> list[str]:
    out = git('status', '--ignored', '--porcelain=v1', cwd=root)
    return sorted(line[3:] for line in out.splitlines() if line.startswith('!! '))


def disposition(path: str, manifest: dict) -> str | None:
    for pattern, value in manifest.items():
        if fnmatch.fnmatchcase(path, pattern) or fnmatch.fnmatchcase(path.rstrip('/'), pattern.rstrip('/')):
            return value if isinstance(value, str) else value.get('disposition')
    if any(fnmatch.fnmatchcase(path, pattern) for pattern in REPRODUCIBLE):
        return 'reproducible'
    return None


def cmd_deletion_check(args: argparse.Namespace) -> int:
    manifest = json.loads(args.manifest.read_text()) if args.manifest else {}
    trees = [describe(entry) for entry in worktrees()]
    open_items = []
    for tree in trees:
        if tree.get('uncommitted'):
            open_items.append(f"uncommitted changes in {tree['path']}: {', '.join(tree['uncommitted'][:5])}")
        if tree.get('unpushed_commits'):
            open_items.append(f"{tree['unpushed_commits']} unpushed commit(s) in {tree['path']}")
    for ref in git('for-each-ref', '--format=%(refname:short)', 'refs/heads').split():
        if count := unpushed(f'refs/heads/{ref}'):
            open_items.append(f'branch {ref} has {count} commit(s) on no remote')
    if git('stash', 'list').strip():
        open_items.append('git stash is not empty')
    processes = live_processes(ROOT)
    open_items += [f"live process {p['pid']} in this checkout: {p.get('argv') or p.get('reason')}" for p in processes]
    ignored = {path: disposition(path, manifest) for path in ignored_paths(ROOT)}
    open_items += [f'ignored path without a disposition: {path}' for path, value in ignored.items() if value is None]
    receipt = {'format': 'DEPLOY-DELETION-CHECK-V1', 'head': head(), 'root': str(ROOT),
               'ready': not open_items, 'open_items': open_items, 'worktrees': trees,
               'live_processes': processes, 'ignored': ignored,
               'manifest': str(args.manifest) if args.manifest else None}
    write_json(READINESS_FILE, receipt)
    for item in open_items:
        print(f'OPEN  {item}')
    print(f'DEPLOY_DELETION_CHECK {"READY" if receipt["ready"] else "NOT_READY"} open={len(open_items)} '
          f'receipt={READINESS_FILE.relative_to(ROOT)}')
    return 0 if receipt['ready'] else 1


# --- finish ----------------------------------------------------------------

def cmd_finish(args: argparse.Namespace) -> int:
    status = run(['bash', 'scripts/run-deploy-stage', '--finish'])
    ledger = [sys.executable, 'scripts/benchmark-history-latest-only.py', '--base', 'origin/main']
    status |= run([*ledger, *(['--apply-parked', str(PARK_DIR)] if PARK_DIR.is_dir() else []), '--write'])
    status |= run([*ledger, '--check'])
    factory('outcome', args.outcome)
    status |= run([sys.executable, 'scripts/factory_ledger.py', 'publish'])
    print(f'DEPLOY_FINISH {"PASS" if status == 0 else "FAIL"} outcome={args.outcome}')
    return 0 if status == 0 else 1


# --- dispatch --------------------------------------------------------------

def delegate(module: str, argv: list[str]) -> int:
    sys.path.insert(0, str(ROOT / 'scripts'))
    return __import__(module).main(argv)


def parser() -> argparse.ArgumentParser:
    top = argparse.ArgumentParser(prog='scripts/deploy', description=__doc__)
    sub = top.add_subparsers(dest='command', required=True)
    sub.add_parser('collect', help='inventory every worktree and unpushed branch on this devbox')
    for name, text in (('fix', 'auto-format and lint-fix the changed files'),
                       ('freeze', 'fix, commit every intended change, run the approval guards')):
        command = sub.add_parser(name, help=text)
        command.add_argument('--base', default='origin/main')
        if name == 'freeze':
            command.add_argument('-m', '--message', help='commit message for uncommitted changes')
    opened = sub.add_parser('open-pr', help='start review cycle 1, push, open (or re-request) the PR')
    opened.add_argument('--title')
    opened.add_argument('--body-file', type=Path)
    sub.add_parser('gates', help='run every selected gate in parallel (scripts/deploy_gates.py)', add_help=False)
    waited = sub.add_parser('review-wait', help='wait for CodeRabbit on the open cycle head')
    waited.add_argument('--timeout', type=int, default=600)
    sub.add_parser('merge', help='prove the merge is allowed, then merge and record the merge commit')
    sub.add_parser('production', help='verify every applicable production lane (scripts/deploy_prod.py)',
                   add_help=False)
    checked = sub.add_parser('deletion-check', help='prove nothing needed lives only on this devbox')
    checked.add_argument('--manifest', type=Path, help='JSON {path-glob: disposition} for preserved records')
    finished = sub.add_parser('finish', help='close timing, publish ledger rows, record the outcome, publish telemetry')
    finished.add_argument('--outcome', choices=['completed', 'blocked'], default='completed')
    return top


COMMANDS = {'collect': cmd_collect, 'fix': cmd_fix, 'freeze': cmd_freeze, 'open-pr': cmd_open_pr,
            'review-wait': cmd_review_wait, 'merge': cmd_merge, 'deletion-check': cmd_deletion_check,
            'finish': cmd_finish}


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] in {'gates', 'production'}:
        return delegate({'gates': 'deploy_gates', 'production': 'deploy_prod'}[argv[0]], argv[1:])
    args = parser().parse_args(argv)
    return COMMANDS[args.command](args)


if __name__ == '__main__':
    raise SystemExit(main())
