#!/usr/bin/env bash
# Per-instance Conductor-compatible identity for cloud-Linux VMs (.cloud-env).
#
# An environment snapshot captures the disk, so every VM booted from it inherits
# the builder's /etc/machine-id and its .cloud-env. Keyed on either, every agent
# cloned from one snapshot shared one workspace name: the same reserved ngrok
# domain (the second stack died with ERR_NGROK_334) and the same per-workspace
# Temporal queue. The kernel boot id is fresh on every booted VM and survives
# pause/resume, so it identifies the instance.

cloud_env_instance_id() {
    local boot_id_file="${ROSE_CLOUD_BOOT_ID_FILE:-/proc/sys/kernel/random/boot_id}"
    local instance_id
    [ -r "$boot_id_file" ] || return 1
    instance_id="$(tr -d '-' < "$boot_id_file" | cut -c1-8)"
    [ -n "$instance_id" ] || return 1
    printf '%s\n' "$instance_id"
}

# ensure_cloud_env <root>
# Writes <root>/.cloud-env unless a native Conductor env is present or the file
# was generated on this instance. Files written by other tooling (the cloudbench
# entrypoints pin their own single-tenant identity) carry no marker and are kept.
ensure_cloud_env() {
    local root="$1"
    local env_file="$root/.cloud-env"
    local instance_id
    local ws_id=""
    local port=""

    instance_id="$(cloud_env_instance_id 2>/dev/null)" || instance_id=""
    if [ -f "$env_file" ]; then
        if ! grep -q '^# rose-cloud-env$' "$env_file" 2>/dev/null \
            || [ -z "$instance_id" ] \
            || grep -qx "# rose-cloud-instance $instance_id" "$env_file"; then
            echo "✅ .cloud-env exists — keeping existing workspace id"
            return 0
        fi
        echo "♻️  .cloud-env was generated on another instance (environment snapshot) — regenerating workspace id"
        port="$(sed -nE 's/^export CONDUCTOR_PORT=([0-9]+)$/\1/p' "$env_file" | head -1)"
    elif [ -n "${CONDUCTOR_PORT:-}" ] && [ -n "${CONDUCTOR_WORKSPACE_NAME:-}" ]; then
        echo "✅ Native Conductor env detected — no .cloud-env needed"
        return 0
    fi

    ws_id="$instance_id"
    if [ -z "$ws_id" ] && [ -r /etc/machine-id ]; then
        ws_id="$(cut -c1-8 /etc/machine-id)"
    fi
    if [ -z "$ws_id" ]; then
        ws_id="$(openssl rand -hex 4 2>/dev/null || date +%s%N | tail -c 9)"
    fi
    local workspace_name="cloud-${ws_id}"
    port="${port:-${CONDUCTOR_PORT:-3001}}"
    # `# rose-cloud-env` must appear in THIS file (not only in shell rc files):
    # scripts/lib/workspace-env.sh trusts a synthetic cloud workspace name only
    # when that marker is present, otherwise it rewrites CONDUCTOR_WORKSPACE_NAME
    # to the checkout basename (e.g. `workspace`) and breaks ngrok domain reuse.
    cat > "$env_file" <<EOF
# rose-cloud-env
# rose-cloud-instance ${instance_id:-unknown}
# Generated by scripts/cloud-build.sh — per-instance, gitignored.
export CONDUCTOR_PORT=${port}
export CONDUCTOR_WORKSPACE_NAME=${workspace_name}
export CONDUCTOR_ROOT_PATH=${root}
EOF
    local env_marker="# rose-cloud-env"
    local source_line="[ -f ${root}/.cloud-env ] && . ${root}/.cloud-env"
    local rc
    for rc in "$HOME/.bashrc" "$HOME/.zshrc" "$HOME/.profile"; do
        [ -f "$rc" ] || continue
        grep -qF "$env_marker" "$rc" || printf '\n%s\n%s\n' "$env_marker" "$source_line" >> "$rc"
    done
    echo "✅ Wrote .cloud-env — CONDUCTOR_WORKSPACE_NAME=$workspace_name PORT=$port"
}
