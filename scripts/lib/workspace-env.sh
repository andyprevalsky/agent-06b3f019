#!/usr/bin/env bash

# Prebuilt cloud snapshots bake in both .cloud-env and /etc/machine-id, so every
# VM booted from one inherits the same workspace name and then contends for the
# same reserved ngrok domain and default Temporal queue. .cloud-env therefore
# records the instance it was minted on and is re-keyed on any other instance.
#
# Cursor Cloud mints one agent-store id per agent: it survives reboot and resume
# but differs on every VM booted from a shared snapshot, so it keeps a rebooted
# VM's name (and with it the DB volume and reserved domain). Without it the
# kernel boot id is the only per-VM signal, and a new boot must be re-keyed.
cloud_env_boot_id() {
  cat /proc/sys/kernel/random/boot_id 2>/dev/null || true
}

# /run lives on the snapshotted disk, so a clone can read the builder's store id
# until its own store daemon starts. Trust the id only while the daemon that
# wrote it is running.
cloud_env_agent_id() {
  local id
  id="$(cloud_env_store_agent_id)"
  [ -n "$id" ] || id="$(cloud_env_boxes_devbox_id)"
  [ -z "$id" ] || printf '%s\n' "$id"
}

cloud_env_store_agent_id() {
  local dir="${CLOUD_ENV_AGENT_STORE_DIR:-/run/agent-store-fuse}" pid cmd
  pid="$(sed -n 's/^pid=//p' "$dir/ready" 2>/dev/null || true)"
  case "$pid" in '' | *[!0-9]*) return 0 ;; esac
  if [ -r "/proc/$pid/cmdline" ]; then
    cmd="$(tr '\0' ' ' <"/proc/$pid/cmdline")"
  else
    # macOS has no /proc; keep the daemon-identity contract testable there.
    cmd="$(ps -p "$pid" -o command= 2>/dev/null || true)"
  fi
  printf '%s\n' "$cmd" | grep -q 'agent-store-fuse' || return 0
  cat "$dir/self-store-id" 2>/dev/null || true
}

# boxes.dev: a snapshot clone keeps the snapshot's kernel boot id, but every devbox
# has its own id (BOXES_DEVBOX=1 is set on all of them). CLOUD_ENV_BOXES_DEVBOX_ID
# overrides the lookup (tests); any failure yields no id.
cloud_env_boxes_devbox_id() {
  if [ "${CLOUD_ENV_BOXES_DEVBOX_ID+x}" = x ]; then
    printf '%s\n' "$CLOUD_ENV_BOXES_DEVBOX_ID"
    return 0
  fi
  [ "${BOXES_DEVBOX:-}" = 1 ] && command -v dvb-onbox >/dev/null 2>&1 || return 0
  local json
  if command -v timeout >/dev/null 2>&1; then
    json="$(timeout 3 dvb-onbox whoami --json 2>/dev/null | tr -d '\n' || true)"
  else
    json="$(dvb-onbox whoami --json 2>/dev/null | tr -d '\n' || true)"
  fi
  printf '%s\n' "$json" | sed -n 's/.*"devboxId"[[:space:]]*:[[:space:]]*"\([A-Za-z0-9_-]*\)".*/\1/p'
}

cloud_env_value() {
  sed -n "s/^export $2=//p" "$1" | tail -n 1
}

cloud_env_selects_system_pg() {
  grep -qx 'export ROSE_USE_SYSTEM_PG=true' "$1"
}

cloud_env_stamp() {
  sed -n "s/^# rose-cloud-$2 //p" "$1" | tail -n 1
}

new_cloud_workspace_name() {
  printf 'cloud-%s\n' "$(od -An -N4 -tx1 /dev/urandom | tr -d ' \n')"
}

# Usage: write_cloud_env file port name root boot_id [agent_id] [extra_line]
# extra_line (e.g. 'export ROSE_USE_SYSTEM_PG=true') is written into the temp file
# BEFORE the atomic mv, so a concurrent reader never sees the file without it.
write_cloud_env() {
  local file="$1" port="$2" name="$3" root="$4" boot_id="$5" agent_id="${6:-}" extra_line="${7:-}" tmp
  tmp="$(mktemp "$file.XXXXXX")"
  {
    printf '# rose-cloud-env\n'
    printf '# Generated by scripts/cloud-build.sh — per-instance, gitignored.\n'
    [ -z "$agent_id" ] || printf '# rose-cloud-agent-id %s\n' "$agent_id"
    [ -z "$boot_id" ] || printf '# rose-cloud-boot-id %s\n' "$boot_id"
    printf 'export CONDUCTOR_PORT=%s\n' "$port"
    printf 'export CONDUCTOR_WORKSPACE_NAME=%s\n' "$name"
    printf 'export CONDUCTOR_ROOT_PATH=%s\n' "$root"
    [ -z "$extra_line" ] || printf '%s\n' "$extra_line"
  } >"$tmp"
  mv -f "$tmp" "$file"
}

# Same instance: matching agent ids when both are known; otherwise the same boot
# (a store daemon restart cannot tell a clone from a reboot, so it never re-keys
# within a boot). Files from the earlier boot-id-only writer record the boot as
# ROSE_CLOUD_BOOT_ID instead of a stamp.
cloud_env_instance_matches() {
  local file="$1" agent_id="$2" boot_id="$3" recorded_agent recorded_boot
  recorded_agent="$(cloud_env_stamp "$file" agent-id)"
  if [ -n "$agent_id" ] && [ -n "$recorded_agent" ]; then
    [ "$agent_id" = "$recorded_agent" ]
    return
  fi
  recorded_boot="$(cloud_env_stamp "$file" boot-id)"
  [ -n "$recorded_boot" ] || recorded_boot="$(cloud_env_value "$file" ROSE_CLOUD_BOOT_ID)"
  [ -n "$boot_id" ] && [ "$recorded_boot" = "$boot_id" ]
}

cloud_env_stamps_current() {
  local file="$1" agent_id="$2" boot_id="$3"
  cloud_env_instance_matches "$file" "$agent_id" "$boot_id" || return 1
  [ -z "$agent_id" ] || [ "$(cloud_env_stamp "$file" agent-id)" = "$agent_id" ] || return 1
  [ "$(cloud_env_stamp "$file" boot-id)" = "$boot_id" ]
}

# Usage: refresh_cloud_env_identity [file] [agent_id] [boot_id]; omitted ids are
# read from this VM, an explicit empty id means "unavailable".
refresh_cloud_env_identity() {
  local file="${1:-.cloud-env}" agent_id boot_id
  if [ "$#" -ge 2 ]; then agent_id="$2"; else agent_id="$(cloud_env_agent_id)"; fi
  if [ "$#" -ge 3 ]; then boot_id="$3"; else boot_id="$(cloud_env_boot_id)"; fi
  [ -f "$file" ] || return 0
  [ -n "$agent_id" ] || [ -n "$boot_id" ] || return 0
  cloud_env_stamps_current "$file" "$agent_id" "$boot_id" && return 0
  # Parallel deploy lanes reach this together; the lock plus re-check keeps one
  # re-key per instance. Waiters hold the replaced inode, so they re-read by path.
  (
    if command -v flock >/dev/null 2>&1; then flock 9; fi
    cloud_env_stamps_current "$file" "$agent_id" "$boot_id" && exit 0
    local stale_name port root name
    stale_name="$(cloud_env_value "$file" CONDUCTOR_WORKSPACE_NAME)"
    port="$(cloud_env_value "$file" CONDUCTOR_PORT)"
    root="$(cloud_env_value "$file" CONDUCTOR_ROOT_PATH)"
    [ -n "$root" ] || root="$(cd "$(dirname "$file")" && pwd -P)"
    if [ -n "$stale_name" ] && cloud_env_instance_matches "$file" "$agent_id" "$boot_id"; then
      name="$stale_name"
    else
      name="$(new_cloud_workspace_name)"
      echo "Re-keyed $file minted on another instance: CONDUCTOR_WORKSPACE_NAME ${stale_name:-unset} -> $name" >&2
    fi
    # The system-Postgres selection (boxes/E2B startup scripts) is not identity:
    # it rides in the same atomic rewrite, never as a second append.
    local keep_pg=""
    ! cloud_env_selects_system_pg "$file" || keep_pg='export ROSE_USE_SYSTEM_PG=true'
    write_cloud_env "$file" "${port:-3001}" "$name" "$root" "$boot_id" "$agent_id" "$keep_pg"
  ) 9<"$file"
}

normalize_conductor_workspace_env() {
  local pwd_physical workspace_physical actual_name deploy_worktree_env cloud_name

  # Cloud builds intentionally generate a stable synthetic workspace name in
  # .cloud-env; do not replace it with the checkout directory basename. Shells
  # opened before a re-key still export the old name, so the file wins unless
  # the caller pinned its own identity.
  if [ -f ".cloud-env" ] && grep -q '^# rose-cloud-env$' ".cloud-env" 2>/dev/null; then
    refresh_cloud_env_identity ".cloud-env"
    cloud_name="$(cloud_env_value ".cloud-env" CONDUCTOR_WORKSPACE_NAME)"
    if [ -n "$cloud_name" ] && [ "${ROSE_TRUST_CONDUCTOR_WORKSPACE_NAME:-}" != "1" ] \
      && [ "${BENCHMARK_ISOLATED_RUN:-false}" != "true" ]; then
      export CONDUCTOR_WORKSPACE_NAME="$cloud_name"
    fi
    return 0
  fi

  pwd_physical="$(cd "$PWD" && pwd -P)"
  deploy_worktree_env="$pwd_physical/.context/deploy-worktree.env"
  if [ -f "$deploy_worktree_env" ] && [ "${BENCHMARK_ISOLATED_RUN:-false}" != "true" ] \
    && [ "${ROSE_STABILITY_UNIT_IDENTITY:-}" != "1" ]; then
    # /descend-created deploy worktrees are not registered with Conductor and
    # otherwise inherit their controller's identity and port range. Rehydrate
    # the durable child identity on every new shell before resolving resources.
    # A nested benchmark run already owns a separately reserved identity and
    # port range; rehydrating the parent here would collapse both stacks onto
    # the deploy database. So does a new-test stability unit
    # (select_affected_tests.py --stability): each concurrent backend unit owns
    # its own victoria_<identity> database.
    . "$deploy_worktree_env"
    if [ "${ROSE_DEPLOY_WORKTREE_PATH:-}" != "$pwd_physical" ]; then
      echo "Deploy worktree config belongs to ${ROSE_DEPLOY_WORKTREE_PATH:-unknown}, not $pwd_physical." >&2
      return 1
    fi
    export CONDUCTOR_WORKSPACE_PATH="$pwd_physical"
    export CONDUCTOR_WORKSPACE_NAME
    export CONDUCTOR_PORT
  fi

  if [ -n "${CONDUCTOR_WORKSPACE_PATH:-}" ] && [ -d "$CONDUCTOR_WORKSPACE_PATH" ]; then
    workspace_physical="$(cd "$CONDUCTOR_WORKSPACE_PATH" && pwd -P)"
  else
    workspace_physical="$pwd_physical"
  fi

  if [ "$workspace_physical" != "$pwd_physical" ]; then
    if [ -z "${CONDUCTOR_WORKSPACE_NAME:-}" ]; then
      export CONDUCTOR_WORKSPACE_NAME
      CONDUCTOR_WORKSPACE_NAME="$(basename "$pwd_physical")"
    fi
    return 0
  fi

  actual_name="$(basename "$workspace_physical")"
  if [ -z "${CONDUCTOR_WORKSPACE_NAME:-}" ]; then
    export CONDUCTOR_WORKSPACE_NAME="$actual_name"
    export CONDUCTOR_WORKSPACE_PATH="$workspace_physical"
    return 0
  fi

  if [ "$CONDUCTOR_WORKSPACE_NAME" != "$actual_name" ] && [ "${ROSE_TRUST_CONDUCTOR_WORKSPACE_NAME:-}" != "1" ]; then
    echo "Warning: CONDUCTOR_WORKSPACE_NAME=$CONDUCTOR_WORKSPACE_NAME does not match workspace path $workspace_physical; using $actual_name for local resources."
    export CONDUCTOR_WORKSPACE_NAME="$actual_name"
  fi
  export CONDUCTOR_WORKSPACE_PATH="$workspace_physical"
}

# Usage: benchmark_system_pg_db_name <native run id>
# PostgreSQL truncates identifiers after63bytes. Hash long native identities
# before creation so sibling worlds cannot share the truncated prefix.
benchmark_system_pg_db_name() {
  python3 - "${1:?benchmark run id required}" <<'PY_BENCHMARK_DATABASE'
import hashlib
import re
import sys

run_id = sys.argv[1]
name = "victoria_bench_" + re.sub(r"[^A-Za-z0-9]", "_", run_id)
if len(name) > 63:
    name = name[:46] + "_" + hashlib.sha256(run_id.encode()).hexdigest()[:16]
print(name)
PY_BENCHMARK_DATABASE
}

# Usage: workspace_system_pg_db_name [root]
# Prints the system-Postgres database a non-benchmark stack may reset and seed.
# localhost:5432 is ONE server shared by every workspace on the host, so a
# named workspace gets victoria_stack_<workspace> (distinct from the
# victoria_<workspace> test-fixture database). The shared `victoria` is kept
# only for an unset workspace, the single-tenant cloud identity recorded in
# <root>/.cloud-env (same name AND port — the database cloud-init seeds), or an
# explicit ROSE_SYSTEM_PG_DB_NAME. Another stack on a cloud VM inherits the
# .cloud-env name, so its port keeps its database separate.
workspace_system_pg_db_name() {
  local root="${1:-.}" name="${CONDUCTOR_WORKSPACE_NAME:-}" suffix="" safe
  if [ -n "${ROSE_SYSTEM_PG_DB_NAME:-}" ]; then
    if ! [[ "$ROSE_SYSTEM_PG_DB_NAME" =~ ^[a-z_][a-z0-9_]{0,62}$ ]]; then
      echo "❌ ROSE_SYSTEM_PG_DB_NAME must match ^[a-z_][a-z0-9_]{0,62}\$; got '$ROSE_SYSTEM_PG_DB_NAME'." >&2
      return 1
    fi
    printf '%s\n' "$ROSE_SYSTEM_PG_DB_NAME"
    return 0
  fi
  if [ -z "$name" ]; then
    printf 'victoria\n'
    return 0
  fi
  if [ -f "$root/.cloud-env" ] && grep -qx '# rose-cloud-env' "$root/.cloud-env" 2>/dev/null \
    && [ "$name" = "$(cloud_env_value "$root/.cloud-env" CONDUCTOR_WORKSPACE_NAME)" ]; then
    if [ "${CONDUCTOR_PORT:-}" = "$(cloud_env_value "$root/.cloud-env" CONDUCTOR_PORT)" ]; then
      printf 'victoria\n'
      return 0
    fi
    suffix="_p$(printf '%s' "${CONDUCTOR_PORT:-}" | tr -cd '0-9')"
  fi
  safe="$(printf '%s' "$name" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9' '_' | cut -c1-40)"
  printf 'victoria_stack_%s%s\n' "$safe" "$suffix"
}

# Usage: ensure_cloud_workspace_env <root> [port] [boot_id_file]
# Provisions <root>/.cloud-env for cloud-build.sh: an existing file is re-keyed
# only when another instance minted it, and native Conductor workspaces are
# left alone. The `# rose-cloud-env` marker must be in this file, not only in
# shell rc files: normalize_conductor_workspace_env trusts a synthetic name only
# when it is present, and otherwise rewrites it to the checkout basename.
ensure_cloud_workspace_env() {
  local root="$1" port="${2:-3001}" boot_id_file="${3:-}"
  local env_file="$root/.cloud-env" boot_id agent_id rc
  local env_marker="# rose-cloud-env" source_line="[ -f $root/.cloud-env ] && . $root/.cloud-env"

  if [ -n "$boot_id_file" ]; then
    boot_id="$(tr -d '[:space:]' <"$boot_id_file" 2>/dev/null || true)"
  else
    boot_id="$(cloud_env_boot_id)"
  fi
  agent_id="$(cloud_env_agent_id)"
  if [ -f "$env_file" ]; then
    refresh_cloud_env_identity "$env_file" "$agent_id" "$boot_id"
  elif [ -n "${CONDUCTOR_PORT:-}" ] && [ -n "${CONDUCTOR_WORKSPACE_NAME:-}" ]; then
    echo "✅ Native Conductor env detected — no .cloud-env needed"
    return 0
  else
    write_cloud_env "$env_file" "$port" "$(new_cloud_workspace_name)" "$root" "$boot_id" "$agent_id"
  fi
  for rc in "$HOME/.bashrc" "$HOME/.zshrc" "$HOME/.profile"; do
    [ -f "$rc" ] || continue
    grep -qF "$env_marker" "$rc" || printf '\n%s\n%s\n' "$env_marker" "$source_line" >>"$rc"
  done
  echo "✅ .cloud-env — CONDUCTOR_WORKSPACE_NAME=$(cloud_env_value "$env_file" CONDUCTOR_WORKSPACE_NAME) PORT=$(cloud_env_value "$env_file" CONDUCTOR_PORT)"
}

resolve_temporal_task_queue() {
  local workspace_name="$1"
  printf '%s\n' "${TEMPORAL_TASK_QUEUE:-navi-agent-tasks-$workspace_name}"
}

# Given the intended local DB container name, its target host port, and the
# output of `docker ps --format '{{.Names}} {{.Ports}}'`, print the name of a
# DIFFERENT running container that already binds that host port (empty if none).
#
# This guards against a foreign CONDUCTOR_PORT (e.g. one leaked into a shell by
# a /descend or benchmark run whose mismatched CONDUCTOR_WORKSPACE_NAME was
# normalized away here) deriving the wrong LOCAL_DB_PORT and clobbering a
# sibling workspace's database. Only running containers actually bind the host
# port, so `docker ps` (not `-a`) is the correct input.
db_port_conflict_owner() {
  local self="$1" port="$2" ps_output="$3"
  printf '%s\n' "$ps_output" | awk -v self="$self" -v pat=":${port}->" '
    index($0, pat) { if ($1 != self) { print $1; exit } }
  '
}

# Sandboxes (E2B code agents) reach this backend at ROSE_UI_PUBLISH_BASE_URL:
# `rose display`, `rose-ui` publish/pull, the agent graph and code previews all
# call <base>/api/... . Without it the backend falls back to BACKEND_URL, a
# loopback a sandbox can never reach, so a local code agent's display failed
# (agent-display-revenue-chart, 2026-10-23). When a public tunnel is up, route
# sandboxes through it (the tunnel's Vite server proxies /api to the backend).
# Agent Display iframes keep loading /usercontent from the loopback backend the
# local frontend already uses. An explicit ROSE_UI_PUBLISH_BASE_URL wins.
export_sandbox_backend_base_url() {
  [ -n "${ROSE_UI_PUBLISH_BASE_URL:-}" ] && return 0
  case "${PUBLIC_BASE_URL:-}" in
    https://*) ;;
    *) return 0 ;;
  esac
  export ROSE_UI_PUBLISH_BASE_URL="${PUBLIC_BASE_URL%/}"
  if [ -z "${USERCONTENT_BASE_URL:-}" ] && [ -n "${BACKEND_URL:-}" ]; then
    export USERCONTENT_BASE_URL="$BACKEND_URL"
  fi
}
