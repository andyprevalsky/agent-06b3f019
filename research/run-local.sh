#!/bin/bash
# Run Rose Edge Functions Locally

set -e

# Colors
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

RESEARCH_PORT=${RESEARCH_PORT:-54321}
RESEARCH_DB_PORT=${RESEARCH_DB_PORT:-$(($RESEARCH_PORT + 1))}
RESEARCH_ANALYTICS_PORT=${RESEARCH_ANALYTICS_PORT:-$(($RESEARCH_PORT + 2))}
RESEARCH_VECTOR_PORT=${RESEARCH_VECTOR_PORT:-$(($RESEARCH_PORT + 3))}
RESEARCH_INBUCKET_PORT=${RESEARCH_INBUCKET_PORT:-$(($RESEARCH_PORT + 4))}

# Stop Supabase containers on exit
cleanup() {
    echo -e "\n🛑 Stopping Supabase containers..."
    cd "$(dirname "$0")/supabase" && supabase stop 2>/dev/null
}
trap cleanup EXIT

echo -e "${GREEN}🚀 [Research] Mode: DEVELOPMENT (port=$RESEARCH_PORT)${NC}"
echo -e "${GREEN}   Starting Rose Edge Functions Locally${NC}\n"

# Check if .env exists
if [ ! -f ".env" ]; then
    echo -e "${RED}❌ .env file not found in /research${NC}"
    echo "Create one from .env.example:"
    echo "  cp .env.example .env"
    echo "  # Then edit .env with your values"
    exit 1
fi

# Check if supabase CLI is installed
if ! command -v supabase &> /dev/null; then
    echo -e "${RED}❌ Supabase CLI is not installed${NC}"
    echo "Install it with: npm install -g supabase"
    exit 1
fi

# Generate config.toml with dynamic ports for worktree isolation
echo "Generating supabase/config.toml with port=$RESEARCH_PORT..."
cat > supabase/config.toml <<TOML
# AUTO-GENERATED by run-local.sh — do not edit manually
project_id = "rose-research-${CONDUCTOR_WORKSPACE_NAME:-local}"

[api]
enabled = true
port = ${RESEARCH_PORT}

[db]
port = ${RESEARCH_DB_PORT}

[realtime]
enabled = false

[analytics]
enabled = true
port = ${RESEARCH_ANALYTICS_PORT}
vector_port = ${RESEARCH_VECTOR_PORT}

[inbucket]
enabled = true
port = ${RESEARCH_INBUCKET_PORT}

[studio]
enabled = false

[storage]
enabled = false

[edge_runtime]
enabled = true
policy = "per_worker"

[edge_runtime.secrets]
PROD_SUPABASE_URL = "env(PROD_SUPABASE_URL)"
PROD_SUPABASE_SERVICE_ROLE_KEY = "env(PROD_SUPABASE_SERVICE_ROLE_KEY)"
OPENROUTER_API_KEY = "env(OPENROUTER_API_KEY)"
ANTHROPIC_API_KEY = "env(ANTHROPIC_API_KEY)"
CEREBRAS_API_KEY = "env(CEREBRAS_API_KEY)"
BROWSER_USE_API_KEY = "env(BROWSER_USE_API_KEY)"
YUTORI_API_KEY = "env(YUTORI_API_KEY)"

[functions.completions]
verify_jwt = false

[functions.chat]
verify_jwt = false

[functions.cost]
verify_jwt = false

[functions.api-keys]
verify_jwt = false

[functions.generate-api-key]
verify_jwt = false

[functions.delete-api-key]
verify_jwt = false

[functions.rose-bench]
verify_jwt = false
TOML

# Check if Supabase local services are running (required for functions serve)
# Set SKIP_SUPABASE_START=1 to skip the local stack (auth/realtime/studio/DB).
# Edge functions hit prod Supabase for DB ops via PROD_SUPABASE_URL, so the
# local stack is only needed when testing auth/realtime locally — skip it in
# sandboxes where Docker is unavailable (Cord, Codespaces without DinD, etc.).
echo "Checking if Supabase is running..."
cd supabase
if [ "${SKIP_SUPABASE_START:-0}" = "1" ] || ! docker ps &>/dev/null; then
    echo -e "${YELLOW}⚠️  Skipping 'supabase start' (SKIP_SUPABASE_START=1 or Docker unavailable).${NC}"
    echo -e "${YELLOW}   Edge functions will serve standalone against prod Supabase via PROD_SUPABASE_URL.${NC}\n"
elif ! supabase status &> /dev/null; then
    echo -e "${YELLOW}⚠️  Local Supabase is not running. Starting it...${NC}\n"
    MAX_RETRIES=3
    for attempt in $(seq 1 $MAX_RETRIES); do
        if supabase start; then
            echo ""
            echo -e "${GREEN}✅ Supabase started${NC}"
            echo ""
            break
        fi
        if [ "$attempt" -eq "$MAX_RETRIES" ]; then
            echo -e "${RED}❌ supabase start failed after $MAX_RETRIES attempts${NC}"
            exit 1
        fi
        echo -e "${YELLOW}⚠️  supabase start failed (attempt $attempt/$MAX_RETRIES) — retrying in 5s...${NC}"
        supabase stop 2>/dev/null || true
        sleep 5
    done
else
    echo -e "${GREEN}✅ Supabase is already running${NC}\n"
fi
cd ..

# Show environment info
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "Environment:"
if grep -q "OPENROUTER_API_KEY" .env; then
    echo "  ✅ OPENROUTER_API_KEY found"
else
    echo "  ❌ OPENROUTER_API_KEY missing"
fi

if grep -q "SUPABASE_URL" .env; then
    echo "  ✅ SUPABASE_URL found"
else
    echo "  ⚠️  SUPABASE_URL not set (will use localhost)"
fi

if grep -q "SUPABASE_SERVICE_ROLE_KEY" .env; then
    echo "  ✅ SUPABASE_SERVICE_ROLE_KEY found"
else
    echo "  ❌ SUPABASE_SERVICE_ROLE_KEY missing"
fi
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

echo -e "${GREEN}🔧 Starting Edge Functions...${NC}\n"
echo "Functions will be available at:"
echo "  http://localhost:${RESEARCH_PORT}/functions/v1/completions"
echo "  http://localhost:${RESEARCH_PORT}/functions/v1/chat"
echo "  http://localhost:${RESEARCH_PORT}/functions/v1/cost"
echo "  http://localhost:${RESEARCH_PORT}/functions/v1/api-keys"
echo "  http://localhost:${RESEARCH_PORT}/functions/v1/generate-api-key"
echo "  http://localhost:${RESEARCH_PORT}/functions/v1/delete-api-key"
echo "  http://localhost:${RESEARCH_PORT}/functions/v1/rose-bench"
echo ""
echo -e "${YELLOW}Press Ctrl+C to stop${NC}\n"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

# Serve functions with .env from /research
cd supabase
supabase functions serve --env-file ../.env











