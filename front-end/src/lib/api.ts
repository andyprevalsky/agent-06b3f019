// API Functions

// Get all agents
export async function getAllAgents(): Promise<Agent[]> {
  const headers = await getAuthHeaders();
  
  const response = await fetch(`${API_BASE_WITH_PATH}/agents`, {
    headers,
  });

  if (!response.ok) {
    throw new Error('Failed to fetch agents');
  }

  const data = await response.json();
  return data.agents;
}

// Get agent details with messages
export async function getAgent(agentId: string, before?: string): Promise<{
  agent: AgentDetail;
  messages: Message[];
  pagination: {
    has_more: boolean;
    oldest_timestamp: string | null;
  };
}> {
  const headers = await getAuthHeaders();
  const url = before 
    ? `${API_BASE_WITH_PATH}/agents/${agentId}?before=${before}`
    : `${API_BASE_WITH_PATH}/agents/${agentId}`;
  
  const response = await fetch(url, {
    headers,
  });

  if (!response.ok) {
    throw new Error('Failed to fetch agent');
  }

  return await response.json();
}

// Create a new agent
export async function createAgent(payload: CreateAgentPayload): Promise<Agent> {
  const headers = await getAuthHeaders();
  const source = payload.source ?? 'WEB';
  
  const response = await fetch(`${API_BASE_WITH_PATH}/agents`, {
    method: 'POST',
    headers,
    body: JSON.stringify({ ...payload, source }),
  });

  if (!response.ok) {
    const error = await response.json();
    throw new Error(error.error || 'Failed to create agent');
  }

  return await response.json();
}

