#!/usr/bin/env tsx

/**
 * Drift guard for the fake GitHub (tests/helpers/fake-github.ts).
 *
 * The fake must answer a rate limit with exactly what GitHub answered. Its
 * un-parameterised responses are compared to the recorded fixtures byte for
 * byte over real HTTP (status, every header, body bytes), and each fixture
 * must record where it came from. Only `x-ratelimit-reset` and `retry-after`
 * may differ, and only when a test passes them explicitly.
 *
 * Provenance of what the fake serves:
 *  - primary-403.json    CAPTURED from api.github.com (unauthenticated call from an
 *                        IP whose 60/h budget was spent; consumed nothing).
 *  - secondary-403.json  CAPTURED status + body from production logs of the real
 *                        secondary-limit response (headers were not logged).
 *  - git transport       GENERATED by the real git client against the fake (its own
 *                        stderr). GitHub documents no git-transport limit text, so no
 *                        GitHub wording is claimed for git; see
 *                        e2b-templates/claude-code/git-rate-limit.test.mjs.
 */

import assert from 'node:assert/strict';
import {
  loadRateLimitFixture,
  rateLimitResponse,
  startFakeGithub,
  type RateLimitKind,
} from '../helpers/fake-github';

// Headers the HTTP/1.1 server adds around a fixture that does not record them
// (framing, not content). Where a fixture records one, it is compared exactly.
const TRANSPORT_HEADERS = new Set(['connection', 'keep-alive', 'content-length', 'date']);

async function verify(kind: RateLimitKind): Promise<void> {
  const fixture = loadRateLimitFixture(kind);
  assert.ok(
    fixture.source.length > 80 && /real github response/i.test(fixture.source),
    `${kind}: the fixture must record that it is a real response and where it came from`
  );
  assert.match(fixture.documentation, /docs\.github\.com/, `${kind}: cite the GitHub docs`);
  assert.ok([403, 429].includes(fixture.status), `${kind}: a rate limit is a 403 or 429`);

  const fake = await startFakeGithub(() => rateLimitResponse(kind));
  try {
    const response = await fetch(`${fake.baseUrl}/repos/octocat/Hello-World`);
    assert.equal(response.status, fixture.status, `${kind}: status`);
    const got = new Map<string, string>();
    response.headers.forEach((value, name) => got.set(name, value));
    for (const [name, value] of fixture.headers) {
      assert.equal(got.get(name.toLowerCase()), value, `${kind}: header ${name}`);
    }
    const expectedNames = new Set(fixture.headers.map(([name]) => name.toLowerCase()));
    for (const name of got.keys()) {
      assert.ok(
        expectedNames.has(name) || TRANSPORT_HEADERS.has(name),
        `${kind}: the fake invented a header: ${name}`
      );
    }
    const bytes = Buffer.from(await response.arrayBuffer());
    assert.ok(bytes.equals(Buffer.from(fixture.body, 'utf8')), `${kind}: body bytes`);
    assert.equal(got.get('content-length'), String(bytes.length), `${kind}: content-length`);
  } finally {
    await fake.close();
  }
}

async function main(): Promise<void> {
  await verify('primary');
  await verify('secondary');

  // The primary capture is a primary limit: the reset header is present and
  // the budget is spent; the secondary capture carries only a message.
  const primary = loadRateLimitFixture('primary');
  const header = (name: string) => primary.headers.find(([n]) => n === name)?.[1];
  assert.equal(header('x-ratelimit-remaining'), '0');
  assert.equal(header('x-ratelimit-resource'), 'core');
  assert.match(header('x-ratelimit-reset') ?? '', /^\d{10}$/);
  assert.equal(header('retry-after'), undefined, 'the real primary response has no retry-after');
  assert.match(JSON.parse(primary.body).message, /^API rate limit exceeded for /);

  const secondary = loadRateLimitFixture('secondary');
  assert.match(JSON.parse(secondary.body).message, /^You have exceeded a secondary rate limit/);
  assert.equal(
    JSON.parse(secondary.body).documentation_url.includes('secondary-rate-limits'),
    true
  );

  // The two parameterised values are the only ones that may move.
  const moved = rateLimitResponse('primary', { resetEpochS: 4_000_000_000, retryAfterS: 7 });
  const baseline = rateLimitResponse('primary');
  const diff = moved.headers.filter(
    ([name, value]) => baseline.headers.find(([n]) => n === name)?.[1] !== value
  );
  assert.deepEqual(diff.map(([name]) => name).sort(), ['retry-after', 'x-ratelimit-reset']);
  assert.equal(moved.body, baseline.body);

  process.stdout.write(
    'github rate-limit fixtures: fake matches the recorded responses byte for byte\n'
  );
}

main().catch((error) => {
  process.stderr.write(
    `${error instanceof Error ? (error.stack ?? error.message) : String(error)}\n`
  );
  process.exit(1);
});
