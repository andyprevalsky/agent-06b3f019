/**
 * `rose-display` — the in-sandbox CLI a code agent (Claude Code / Codex) runs
 * to show images or videos inline in its own trajectory:
 *
 *   rose-display shot.png demo.mp4 https://example.com/chart.png --caption "Before / after"
 *     └─ one POST per item ─► $ROSE_DISPLAY_URL (Bearer $ROSE_DISPLAY_TOKEN)
 *        local files as base64, URLs fetched server-side; caption on the first.
 *
 * Re-running the same command is safe: the backend dedupes per content hash
 * per agent, so an item is posted at most once.
 */
export const DISPLAY_CLI_NAME = 'rose-display';
export const DISPLAY_CLI_VERSION = '1';
export const DISPLAY_MAX_ITEMS = 20;
export const DISPLAY_MAX_FILE_BYTES = 20 * 1024 * 1024;

export const DISPLAY_CLI_SCRIPT = `#!/usr/bin/env node
'use strict';
// rose-display CLI v${DISPLAY_CLI_VERSION} — generated by Rose; do not edit.
const fs = require('fs');
const path = require('path');

const MAX_ITEMS = ${DISPLAY_MAX_ITEMS};
const MAX_FILE = ${DISPLAY_MAX_FILE_BYTES};

function usage(code) {
  console.log('usage: rose-display <file|url>... [--caption "text"]');
  console.log('Shows images/videos inline in this agent\\'s Rose trajectory (max ' + MAX_ITEMS + ' items, 20 MB each).');
  process.exit(code);
}

function parseArgs(argv) {
  const items = [];
  let caption;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--help' || arg === '-h') usage(0);
    if (arg === '--version') { console.log('${DISPLAY_CLI_VERSION}'); process.exit(0); }
    if (arg === '--caption' || arg === '-c') {
      caption = argv[i + 1];
      if (caption === undefined) throw new Error('--caption needs a value');
      i += 1;
      continue;
    }
    if (arg.startsWith('--caption=')) { caption = arg.slice('--caption='.length); continue; }
    items.push(arg);
  }
  if (items.length === 0) usage(1);
  if (items.length > MAX_ITEMS) throw new Error('at most ' + MAX_ITEMS + ' items per call (got ' + items.length + ')');
  return { items, caption };
}

function toItem(arg) {
  if (/^https?:\\/\\//i.test(arg)) return { label: arg, body: { url: arg } };
  const abs = path.resolve(arg);
  const stat = fs.statSync(abs);
  if (!stat.isFile()) throw new Error(arg + ' is not a regular file');
  if (stat.size > MAX_FILE) throw new Error(arg + ' is larger than 20 MB');
  return {
    label: arg,
    body: { content_base64: fs.readFileSync(abs).toString('base64'), filename: path.basename(abs) },
  };
}

async function main() {
  const url = process.env.ROSE_DISPLAY_URL;
  const token = process.env.ROSE_DISPLAY_TOKEN;
  if (!url || !token) throw new Error('ROSE_DISPLAY_URL and ROSE_DISPLAY_TOKEN must be set (they are injected into Rose code sessions)');
  const { items, caption } = parseArgs(process.argv.slice(2));
  const prepared = items.map(toItem);
  let failed = 0;
  for (let i = 0; i < prepared.length; i += 1) {
    const item = prepared[i];
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + token },
      body: JSON.stringify({ items: [item.body], ...(i === 0 && caption ? { caption } : {}) }),
    });
    const text = await res.text();
    let body;
    try { body = JSON.parse(text); } catch { body = { error: text }; }
    if (!res.ok) {
      failed += 1;
      console.error('rose-display: ' + item.label + ' failed (' + res.status + '): ' + (body.error || text));
      for (const detail of body.details || []) console.error('  - ' + detail);
      continue;
    }
    const result = (body.items || [])[0] || {};
    console.log((result.status === 'duplicate' ? 'already displayed ' : 'displayed ') + item.label + ' (' + (result.mime_type || '?') + ', message ' + result.message_id + ')');
  }
  if (failed > 0) process.exit(1);
}

main().catch((err) => { console.error('rose-display: ' + err.message); process.exit(1); });
`;
