/**
 * The `rose-agents` CLI installed on every code-agent session PATH. How to use
 * it is the agent-graph Rose skill (assets/rose-skills/agent-graph/SKILL.md),
 * listed in the code-agent prompt's table of contents (C17).
 *
 * Kept as a string constant so the compiled backend ships it without an
 * asset-copy step. The usage text is agent-facing (prompt-scoped, CLAUDE.md
 * rule 26): changes need fresh approval.
 *
 *   rose-agents list                 → GET  $ROSE_AGENTS_URL/agents
 *   rose-agents send <id> <message>  → POST $ROSE_AGENTS_URL/messages
 *   rose-agents grep <pattern>       → POST $ROSE_AGENTS_URL/grep
 *   (any call, token near expiry)    → POST $ROSE_AGENTS_URL/token → ~/.rose/agents-token
 */

import { AGENT_ACCOUNT_CLI_SCRIPT } from './cliAccount';

export const AGENT_GRAPH_CLI_NAME = 'rose-agents';
export const AGENT_GRAPH_CLI_VERSION = '4';

export const AGENT_GRAPH_CLI_SCRIPT = `#!/usr/bin/env node
'use strict';
// rose-agents CLI v${AGENT_GRAPH_CLI_VERSION} — generated by Rose; do not edit.
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const USAGE = [
  'usage:',
  '  rose-agents list [--json]',
  '  rose-agents list --scope account [--project ID] [--folder ID] [--limit N] [--cursor CURSOR] [--json]',
  '  rose-agents read <agent_id> [--limit N] [--cursor CURSOR] [--message ID --offset N] [--json]',
  '  rose-agents spawn --project ID --folder ID --title TEXT --goal-file FILE --instruction-file FILE --id KEY [--json]',
  '  rose-agents send <agent_id> <message...|->  [--id <idempotency-key>] [--json]',
  '  rose-agents send <agent_id> <message...|-> --scope account [--id KEY] [--json]',
  '  rose-agents grep <regex> [--agent <agent_id>] [--role USER|ASSISTANT|TOOL] [--limit N] [-i] [--json]',
].join('\\n');

function fail(message, code) {
  process.stderr.write(message + '\\n');
  process.exit(code === undefined ? 1 : code);
}

function parse(argv) {
  const positional = [];
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--json' || arg === '-i') flags[arg.replace(/^-+/, '')] = true;
    else if (arg.startsWith('--')) {
      if (i + 1 >= argv.length) fail('missing value for ' + arg + '\\n' + USAGE, 2);
      flags[arg.slice(2)] = argv[i + 1];
      i += 1;
    } else positional.push(arg);
  }
  return { positional, flags };
}

// The session token is short-lived; a refreshed one is kept here (0600). The
// newer of it and the env token wins: a resumed session starts with a freshly
// minted env token, which must beat a refreshed copy an earlier task left.
const TOKEN_FILE = process.env.ROSE_AGENTS_TOKEN_FILE || path.join(os.homedir(), '.rose', 'agents-token');
const REFRESH_WINDOW_S = 30 * 60;

function storedToken() {
  let refreshed = '';
  try {
    refreshed = fs.readFileSync(TOKEN_FILE, 'utf8').trim();
  } catch (err) {
    // no refreshed token yet
  }
  const minted = process.env.ROSE_AGENTS_TOKEN || '';
  if (!refreshed || !minted) return refreshed || minted;
  return tokenExpiry(refreshed) > tokenExpiry(minted) ? refreshed : minted;
}

function tokenExpiry(token) {
  try {
    const payload = token.slice(token.indexOf('.') + 1).split('.')[0];
    return Number(JSON.parse(Buffer.from(payload, 'base64url').toString('utf8')).exp) || 0;
  } catch (err) {
    return 0;
  }
}

async function request(base, method, route, token, body) {
  const response = await fetch(base.replace(/\\/+$/, '') + route, {
    method,
    headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' },
    body: body === undefined ? undefined : JSON.stringify(body),
    ...(route.startsWith('/account/') ? { signal: AbortSignal.timeout(30000) } : {}),
  });
  if (!route.startsWith('/account/')) return { response, text: await response.text() };
  const reader = response.body?.getReader();
  if (!reader) return { response, text: '' };
  const parts = []; let bytes = 0;
  try {
    while (true) {
      const part = await reader.read();
      if (part.done) break;
      bytes += part.value.byteLength;
      if (bytes > 65536) {
        await reader.cancel();
        throw new Error('Account response exceeds 65536 bytes; request a smaller page');
      }
      parts.push(Buffer.from(part.value));
    }
  } finally { reader.releaseLock(); }
  return { response, text: Buffer.concat(parts).toString('utf8') };
}

async function freshToken(base) {
  const token = storedToken();
  if (!token || tokenExpiry(token) - Date.now() / 1000 > REFRESH_WINDOW_S) return token;
  const { response, text } = await request(base, 'POST', '/token', token);
  if (!response.ok) return token;
  try {
    const next = JSON.parse(text).token;
    if (typeof next !== 'string' || !next) return token;
    fs.mkdirSync(path.dirname(TOKEN_FILE), { recursive: true });
    fs.writeFileSync(TOKEN_FILE, next + '\\n', { mode: 0o600 });
    return next;
  } catch (err) {
    return token;
  }
}

async function call(method, route, body) {
  const base = process.env.ROSE_AGENTS_URL;
  if (!base || !storedToken()) fail('ROSE_AGENTS_URL / ROSE_AGENTS_TOKEN are not set in this session');
  const token = await freshToken(base);
  const { response, text } = await request(base, method, route, token, body);
  let data;
  try {
    data = JSON.parse(text);
  } catch (err) {
    data = { raw: text };
  }
  if (!response.ok) fail('rose-agents: HTTP ' + response.status + ' ' + (data.error || text));
  return data;
}

function readStdin() {
  return new Promise((resolve) => {
    let input = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (chunk) => { input += chunk; });
    process.stdin.on('end', () => resolve(input));
  });
}

function printAgents(data) {
  process.stdout.write('you: ' + data.self_id + '  root: ' + data.root_agent_id + '\\n');
  for (const agent of data.agents) {
    const indent = '  '.repeat(Math.max(0, agent.depth));
    const label = (agent.title || agent.goal || '').replace(/\\s+/g, ' ').slice(0, 100);
    process.stdout.write(
      indent + agent.id + '  [' + agent.kind + (agent.provider ? ':' + agent.provider : '') + '] ' +
        agent.status + '  ' + agent.relation + '  ' + label + '\\n'
    );
  }
}

${AGENT_ACCOUNT_CLI_SCRIPT}

async function main() {
  const [command, ...rest] = process.argv.slice(2);
  if (command === '--help' || command === 'help') { process.stdout.write(USAGE + '\\n'); return; }
  if (await accountCommand(command, rest)) return;
  const { positional, flags } = parse(rest);
  if (command === 'list') {
    const data = await call('GET', '/agents');
    if (flags.json) process.stdout.write(JSON.stringify(data, null, 2) + '\\n');
    else printAgents(data);
    return;
  }
  if (command === 'send') {
    const [to, ...words] = positional;
    if (!to || words.length === 0) fail(USAGE, 2);
    const text = words.length === 1 && words[0] === '-' ? await readStdin() : words.join(' ');
    if (!text.trim()) fail('message is empty', 2);
    const data = await call('POST', '/messages', {
      to,
      text,
      message_id: flags.id || crypto.randomUUID(),
    });
    if (flags.json) process.stdout.write(JSON.stringify(data, null, 2) + '\\n');
    else process.stdout.write('sent ' + data.message_id + ' to ' + data.to.id + ' (' + data.status + ')\\n');
    return;
  }
  if (command === 'grep') {
    const [pattern] = positional;
    if (!pattern) fail(USAGE, 2);
    const data = await call('POST', '/grep', {
      pattern,
      agent_id: flags.agent,
      role: flags.role,
      head_limit: flags.limit ? Number(flags.limit) : undefined,
      case_insensitive: flags.i === true,
    });
    if (flags.json) {
      process.stdout.write(JSON.stringify(data, null, 2) + '\\n');
      return;
    }
    for (const match of data.matches || []) {
      process.stdout.write(match.path + '\\n' + String(match.content).trim() + '\\n\\n');
    }
    process.stdout.write(data.returned + ' of ' + data.total_matches + ' matches\\n');
    return;
  }
  fail(USAGE, command ? 2 : 0);
}

main().catch((err) => fail('rose-agents: ' + (err && err.message ? err.message : String(err))));
`;
